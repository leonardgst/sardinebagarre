/** Les 10 entrées d'un niveau, dans l'ordre de `CONFIGS`. */
export function entriesForLevel(level: Level): readonly ConfigEntry[] {
  return CONFIGS.filter((entry) => entry.level === level);
}

/** Gain maximal d'une configuration : 2^(nombre de 2) × 3^(nombre de 3) (R-10). */
export function maxPayout(entry: ConfigEntry): number {
  return 2 ** entry.twos * 3 ** entry.threes;
}
